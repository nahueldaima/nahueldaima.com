// Extracts the few Iconify icons the site uses into lib/icons.generated.ts,
// so no icon library ships to the browser. Run `npm run icons` after changing ICONS.
import { writeFileSync } from 'node:fs'
import { icons as fa } from '@iconify-json/fa'
import { icons as materialSymbols } from '@iconify-json/material-symbols'
import { icons as mdi } from '@iconify-json/mdi'
import { icons as svgSpinners } from '@iconify-json/svg-spinners'
import { getIconData, iconToSVG } from '@iconify/utils'

const SETS = {
  'fa': fa,
  'material-symbols': materialSymbols,
  'mdi': mdi,
  'svg-spinners': svgSpinners,
}

const ICONS = [
  'fa:github',
  'fa:linkedin-square',
  'fa:twitter-square',
  'fa:rss',
  'material-symbols:dark-mode-rounded',
  'material-symbols:light-mode-rounded',
  'material-symbols:menu-rounded',
  'mdi:chevron-down',
  'mdi:star-three-points-outline',
  'svg-spinners:180-ring',
]

const out = {}
for (const name of ICONS) {
  const [prefix, icon] = name.split(':')
  const data = getIconData(SETS[prefix], icon)
  if (!data)
    throw new Error(`Icon not found: ${name}`)
  const { attributes, body } = iconToSVG(data)
  out[name] = { viewBox: attributes.viewBox, body }
}

writeFileSync(
  new URL('../lib/icons.generated.ts', import.meta.url),
  `// Generated by scripts/build-icons.mjs. Do not edit.\nexport const ICONS = ${JSON.stringify(out, null, 2)} as const\n\nexport type IconName = keyof typeof ICONS\n`,
)
console.log(`Wrote ${ICONS.length} icons`)
